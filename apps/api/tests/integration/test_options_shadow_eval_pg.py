def _seed_chain(
    s: Session, *,
    run_date: dt.date,
    underlying: str = "SPY",
    option_symbol: str = "SPY260515C500",
    expiry: dt.date | None = None,
    strike: float = 500.0,
    option_type: str = "call",
    bid: float | None = 1.50,
    ask: float | None = 1.55,
    open_interest: int | None = 1500,
    volume: int | None = 200,
    delta: float | None = 0.45,
    gamma: float | None = 0.02,
    theta: float | None = -0.05,
    vega: float | None = 0.12,
    iv: float | None = 0.22,
):
    expiry = expiry or (run_date + dt.timedelta(days=21))
    s.execute(text(
        """
        INSERT INTO options_chain_snapshot
          (snapshot_at_utc, underlying, expiry, strike, option_type,
           option_symbol, bid, ask, mid, last, volume, open_interest,
           delta, gamma, theta, vega, iv,
           quote_age_seconds, provider)
        VALUES
          (:ts, :u, :exp, :k, :ot,
           :sym, :bid, :ask, :mid, :last, :vol, :oi,
           :delta, :gamma, :theta, :vega, :iv,
           1, 'test')
        """
    ), {
        "ts": dt.datetime.combine(
            run_date, dt.time(20, 0), tzinfo=dt.timezone.utc,
        ),
        "u": underlying, "exp": expiry, "k": strike, "ot": option_type,
        "sym": option_symbol, "bid": bid, "ask": ask,
        "mid": (
            (bid + ask) / 2 if bid is not None and ask is not None else None
        ),
        "last": ask, "vol": volume, "oi": open_interest,
        "delta": delta, "gamma": gamma, "theta": theta,
        "vega": vega, "iv": iv,
    })
    s.commit()


def _seed_feature(
    s: Session, *, run_date: dt.date, underlying: str = "SPY",
    iv_rank: float | None = 0.35,
):
    s.execute(text(
        """
        INSERT INTO options_feature_daily
          (as_of_date, underlying, iv_rank_252d, atm_iv,
           realized_vol_30d, vrp_30d, term_structure_30_60)
        VALUES (:d, :u, :ivr, 0.22, 0.18, 0.04, 0.01)
        """
    ), {"d": run_date, "u": underlying, "ivr": iv_rank})
    s.commit()


def _row_count(s: Session, table: str) -> int:
    return int(s.execute(text(f"SELECT count(*) FROM {table}"))
                .scalar_one() or 0)


