def test_migration_creates_unique_constraint(session):
    d = dt.date(2026, 5, 1)
    _seed_chain(session, run_date=d)
    _seed_feature(session, run_date=d)
    from apps.api.src.options.shadow_evaluator import evaluate
    evaluate(session, run_date=d)
    # Direct duplicate INSERT must be blocked by ux constraint.
    with pytest.raises(IntegrityError):
        session.execute(text(
            """
            INSERT INTO options_shadow_decision_log
              (run_date, underlying_symbol, option_symbol, expiration,
               strike, option_type, side, strategy_name,
               would_trade, reason,
               liquidity_pass, spread_pass, open_interest_pass,
               volume_pass, greeks_pass, iv_rank_pass, risk_pass)
            VALUES (:d, 'SPY', 'SPY260515C500', :exp,
                    500, 'call', 'buy', 'options_shadow_v1',
                    TRUE, 'duplicate',
                    TRUE, TRUE, TRUE, TRUE, TRUE, TRUE, TRUE)
            """
        ), {"d": d, "exp": d + dt.timedelta(days=21)})
        session.flush()
    session.rollback()


