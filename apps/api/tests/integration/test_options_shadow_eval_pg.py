def test_no_writes_to_execution_tables(session):
    """Most important safety property — the evaluator must NEVER
    cause a row to land in options_paper_trade, paper_trade, or
    paper_position."""
    d = dt.date(2026, 5, 1)
    _seed_chain(session, run_date=d)
    _seed_feature(session, run_date=d)

    n_opt_paper_before = _row_count(session, "options_paper_trade")
    n_paper_before = _row_count(session, "paper_trade")
    n_pos_before = _row_count(session, "paper_position")

    from apps.api.src.options.shadow_evaluator import evaluate
    evaluate(session, run_date=d)

    assert _row_count(session, "options_paper_trade") == n_opt_paper_before
    assert _row_count(session, "paper_trade") == n_paper_before
    assert _row_count(session, "paper_position") == n_pos_before


def test_clean_chain_writes_one_would_trade_row(session):
    d = dt.date(2026, 5, 1)
    _seed_chain(session, run_date=d)
    _seed_feature(session, run_date=d)
    from apps.api.src.options.shadow_evaluator import evaluate
    summary, decisions = evaluate(session, run_date=d)
    assert summary.contracts_evaluated == 1
    assert summary.would_trade_count == 1
    row = session.execute(text(
        "SELECT would_trade, liquidity_pass, spread_pass, "
        "       open_interest_pass, greeks_pass, iv_rank_pass, "
        "       risk_pass, reason "
        "FROM options_shadow_decision_log"
    )).mappings().first()
    assert row["would_trade"] is True
    assert row["liquidity_pass"] is True
    assert row["spread_pass"] is True
    assert row["open_interest_pass"] is True
    assert row["greeks_pass"] is True
    assert row["iv_rank_pass"] is True
    assert row["risk_pass"] is True
    assert row["reason"] == "all_filters_pass"


